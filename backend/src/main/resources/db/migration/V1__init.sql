-- Initial LMS schema. Kept to standard SQL so it also runs on H2 (PostgreSQL mode) in tests.

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(160) not null unique,
    password      varchar(100) not null,
    full_name     varchar(120) not null,
    role          varchar(20)  not null,
    headline      varchar(160),
    bio           text,
    active        boolean      not null default true,
    created_at    timestamp with time zone not null
);

create table categories (
    id    bigint generated by default as identity primary key,
    name  varchar(80)  not null unique,
    slug  varchar(100) not null unique
);

create table courses (
    id              bigint generated by default as identity primary key,
    instructor_id   bigint       not null references users (id),
    category_id     bigint       references categories (id),
    title           varchar(160) not null,
    slug            varchar(180) not null unique,
    subtitle        varchar(255),
    description     text,
    what_you_learn  text,
    level           varchar(20)  not null,
    price           numeric(19, 2) not null default 0,
    thumbnail_file  varchar(120),
    status          varchar(20)  not null,
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    published_at    timestamp with time zone
);
create index idx_courses_status on courses (status);
create index idx_courses_instructor on courses (instructor_id);

create table sections (
    id         bigint generated by default as identity primary key,
    course_id  bigint       not null references courses (id) on delete cascade,
    title      varchar(160) not null,
    position   int          not null
);
create index idx_sections_course on sections (course_id);

create table lessons (
    id                       bigint generated by default as identity primary key,
    section_id               bigint       not null references sections (id) on delete cascade,
    title                    varchar(160) not null,
    type                     varchar(20)  not null,
    position                 int          not null,
    duration_minutes         int,
    free_preview             boolean      not null default false,
    video_url                varchar(500),
    content                  text,
    file_name                varchar(120),
    original_file_name       varchar(255),
    passing_score            int,
    assignment_instructions  text
);
create index idx_lessons_section on lessons (section_id);

create table quiz_questions (
    id           bigint generated by default as identity primary key,
    lesson_id    bigint not null references lessons (id) on delete cascade,
    text         text   not null,
    explanation  text,
    position     int    not null
);

create table quiz_options (
    id           bigint generated by default as identity primary key,
    question_id  bigint       not null references quiz_questions (id) on delete cascade,
    text         varchar(500) not null,
    correct      boolean      not null,
    position     int          not null
);

create table enrollments (
    id            bigint generated by default as identity primary key,
    user_id       bigint not null references users (id),
    course_id     bigint not null references courses (id),
    enrolled_at   timestamp with time zone not null,
    completed_at  timestamp with time zone,
    constraint uq_enrollment unique (user_id, course_id)
);

create table lesson_progress (
    id             bigint generated by default as identity primary key,
    enrollment_id  bigint not null references enrollments (id) on delete cascade,
    lesson_id      bigint not null references lessons (id) on delete cascade,
    completed_at   timestamp with time zone not null,
    constraint uq_lesson_progress unique (enrollment_id, lesson_id)
);

create table quiz_attempts (
    id             bigint generated by default as identity primary key,
    enrollment_id  bigint not null references enrollments (id) on delete cascade,
    lesson_id      bigint not null references lessons (id) on delete cascade,
    score          int     not null,
    correct_count  int     not null,
    total_count    int     not null,
    passed         boolean not null,
    answers        text    not null,
    submitted_at   timestamp with time zone not null
);
create index idx_quiz_attempts on quiz_attempts (enrollment_id, lesson_id);

create table assignment_submissions (
    id                  bigint generated by default as identity primary key,
    enrollment_id       bigint       not null references enrollments (id) on delete cascade,
    lesson_id           bigint       not null references lessons (id) on delete cascade,
    file_name           varchar(120) not null,
    original_file_name  varchar(255) not null,
    note                text,
    status              varchar(20)  not null,
    grade               int,
    feedback            text,
    submitted_at        timestamp with time zone not null,
    graded_at           timestamp with time zone,
    graded_by           varchar(160)
);
create index idx_submissions on assignment_submissions (enrollment_id, lesson_id);

create table orders (
    id                bigint generated by default as identity primary key,
    order_code        varchar(60)    not null unique,
    user_id           bigint         not null references users (id),
    course_id         bigint         not null references courses (id),
    amount            numeric(19, 2) not null,
    status            varchar(20)    not null,
    provider          varchar(20)    not null,
    payment_type      varchar(60),
    snap_token        varchar(255),
    redirect_url      varchar(500),
    created_at        timestamp with time zone not null,
    paid_at           timestamp with time zone,
    last_notification text
);
create index idx_orders_user on orders (user_id);

create table certificates (
    id             bigint generated by default as identity primary key,
    code           varchar(40)  not null unique,
    enrollment_id  bigint       not null unique references enrollments (id),
    student_name   varchar(120) not null,
    course_title   varchar(160) not null,
    instructor_name varchar(120) not null,
    issued_at      timestamp with time zone not null
);
